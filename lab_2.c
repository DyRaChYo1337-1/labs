#include <stdio.h>
#include <math.h>

int main() {
    // Оголошення та ініціалізація спільних вхідних змінних
    double x = 0.0, y = 0.0, R1 = 0.0, R2 = 0.0;
    
    // Оголошення змінних для збереження результатів кожного виразу
    double res1 = 0.0, res2 = 0.0, res3 = 0.0, res4 = 0.0, res5 = 0.0;

    // Введення спільних змінних один раз на початку програми
    printf("Введіть значення x: ");
    scanf("%lf", &x);
    printf("Введіть значення y: ");
    scanf("%lf", &y);
    printf("Введіть значення R1: ");
    scanf("%lf", &R1);
    printf("Введіть значення R2: ");
    scanf("%lf", &R2);
    
    printf("\n--- Результати обчислень ---\n");

    // Завдання 1 (Вираз 6)
    // ОДЗ: x + 1 >= 0 та x - 1 >= 0, отже x >= 1
    if (x >= 1.0) {
        res1 = sin(sqrt(x + 1.0)) - sin(sqrt(x - 1.0));
        printf("Завдання 1 (Вираз 6): %.4lf\n", res1);
    } else {
        printf("Завдання 1 (Вираз 6): Помилка ОДЗ (x має бути >= 1)\n");
    }

    // Завдання 2 (Вираз 13)
    // ОДЗ: обмежень для дійсних чисел немає
    res2 = pow(2.0, -x) - cos(x) + sin(2.0 * x * y);
    printf("Завдання 2 (Вираз 13): %.4lf\n", res2);

    // Завдання 3 (Вираз 32)
    // ОДЗ: знаменники не можуть дорівнювати 0
    if (R1 != 0.0 && R2 != 0.0) {
        res3 = (1.0 / R1) + (1.0 / R2);
        printf("Завдання 3 (Вираз 32): %.4lf\n", res3);
    } else {
        printf("Завдання 3 (Вираз 32): Помилка ОДЗ (R1 та R2 не можуть дорівнювати 0)\n");
    }

    // Завдання 4 (Вираз 9)
    // ОДЗ: знаменник x - 1 != 0. Крім того, для функції pow(base, exp) 
    // база степеня (x+1)/(x-1) не повинна бути від'ємною при довільному x.
    if (x != 1.0 && (x + 1.0) / (x - 1.0) >= 0.0) {
        res4 = pow((x + 1.0) / (x - 1.0), x) + 18.0 * x * pow(y, 2.0);
        printf("Завдання 4 (Вираз 9): %.4lf\n", res4);
    } else {
        printf("Завдання 4 (Вираз 9): Помилка ОДЗ (x != 1, а база степеня має бути >= 0)\n");
    }

    // Завдання 5 (Вираз 10)
    // ОДЗ: x != 0. База степеня (1 + 1/x^2) завжди > 0 для будь-якого x != 0.
    if (x != 0.0) {
        res5 = pow(1.0 + (1.0 / (x * x)), x) - 12.0 * x * x * y;
        printf("Завдання 5 (Вираз 10): %.4lf\n", res5);
    } else {
        printf("Завдання 5 (Вираз 10): Помилка ОДЗ (x не може дорівнювати 0)\n");
    }

    return 0;
}